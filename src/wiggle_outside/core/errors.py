# The enum stays stable, so codes that v1 never returns are members too. The contract test
# compares this set with the rows ERROR-HANDLING section 2 marks "not in v1", "inactive"
# or "not reached in v1" (CONTRACTS section 3).
NOT_IN_V1: Final[frozenset[ErrorCode]] = frozenset(
    {
        ErrorCode.PROGRESS_DISCONNECTED,
        ErrorCode.JOB_CANCEL_REQUESTED,
        ErrorCode.JOB_CANCELLED,
        ErrorCode.RESULT_EXPIRED,
        ErrorCode.REPLAY_FIXTURE_MISSING,
    }
)


