    LOCATION_CHOICE_EXPIRED = "LOCATION_CHOICE_EXPIRED"
    LOCATION_NOT_FOUND = "LOCATION_NOT_FOUND"
    GEOCODER_UNAVAILABLE = "GEOCODER_UNAVAILABLE"
    WEATHER_UNAVAILABLE = "WEATHER_UNAVAILABLE"
    WEATHER_RESTRICTED = "WEATHER_RESTRICTED"
    PLACES_CACHED = "PLACES_CACHED"
    PLACES_UNAVAILABLE = "PLACES_UNAVAILABLE"
    DAYLIGHT_NIGHT = "DAYLIGHT_NIGHT"
    DAYLIGHT_TOO_SHORT = "DAYLIGHT_TOO_SHORT"
    NO_MATCHES = "NO_MATCHES"
    FEWER_MATCHES = "FEWER_MATCHES"
    MODEL_FALLBACK = "MODEL_FALLBACK"
    SERVICE_LIMIT_REACHED = "SERVICE_LIMIT_REACHED"
    SERVICE_UNAVAILABLE = "SERVICE_UNAVAILABLE"
