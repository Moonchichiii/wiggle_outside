#!/usr/bin/env pwsh
# Write gates.lock: the SHA-256 of every protected input (BUILD-PACKAGES section 2.1).
#
# The integration owner runs this; Mats signs the commit that updates gates.lock
# (PLAN section 8). The gate-integrity check compares a pull request's protected inputs
# with main's gates.lock - that check arrives with WP9b (TC-006), so until then this file
# plus Mats's signature is the whole control.
#
# -Verify compares without writing, and exits 1 on any difference.

[CmdletBinding()]
param(
    [switch]$Verify
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$RepoRoot = Split-Path -Parent $PSScriptRoot
$LockPath = Join-Path $RepoRoot 'gates.lock'

# BUILD-PACKAGES section 2.1. Globs are resolved relative to the repository root.
# Paths that do not exist yet (WP2's catalogue, WP9b's configs) are recorded as absent,
# so adding one later changes the lock and needs Mats's signature.
$Protected = @(
    'scripts/check.ps1'
    'scripts/release.ps1'
    'scripts/check_contrast.py'
    'scripts/gates_lock.ps1'
    'ruff.toml'
    'mypy.ini'
    'pytest.ini'
    '.importlinter'
    'biome.json'
    '.djlintrc'
    '.stylelintrc.json'
    'pyproject.toml'
    'uv.lock'
    'package.json'
    'bun.lock'
    'bunfig.toml'
    '.python-version'
    '.gitattributes'
    'AGENTS.md'
    'CLAUDE.md'
    'src/wiggle_outside/planner/activities.toml'
    'src/wiggle_outside/planner/hooks.toml'
)

# Directory trees whose every file is protected.
$ProtectedTrees = @(
    '.github'
    'tests/policy'
)

function Get-FileDigest {
    param([Parameter(Mandatory)][string]$FullPath)
    # Hash the bytes on disk. .gitattributes keeps the working tree at LF, so this digest
    # matches what CI hashes on Linux.
    (Get-FileHash -Path $FullPath -Algorithm SHA256).Hash.ToLowerInvariant()
}

$entries = [System.Collections.Generic.List[string]]::new()

foreach ($rel in ($Protected | Sort-Object)) {
    $full = Join-Path $RepoRoot $rel
    if (Test-Path -LiteralPath $full -PathType Leaf) {
        $entries.Add("$(Get-FileDigest $full)  $rel")
    }
    else {
        $entries.Add("absent                                                            $rel")
    }
}

foreach ($tree in ($ProtectedTrees | Sort-Object)) {
    $root = Join-Path $RepoRoot $tree
    if (-not (Test-Path -LiteralPath $root)) {
        $entries.Add("absent                                                            $tree/")
        continue
    }
    # @() so an empty or single-file tree still has .Count under Set-StrictMode.
    $files = @(Get-ChildItem -Path $root -File -Recurse | Sort-Object FullName)
    if ($files.Count -eq 0) {
        $entries.Add("absent                                                            $tree/")
        continue
    }
    foreach ($file in $files) {
        $rel = [System.IO.Path]::GetRelativePath($RepoRoot, $file.FullName).Replace('\', '/')
        $entries.Add("$(Get-FileDigest $file.FullName)  $rel")
    }
}

$header = @(
    '# gates.lock - SHA-256 of every protected input (BUILD-PACKAGES section 2.1).'
    '# Generated by scripts/gates_lock.ps1. Mats signs the commit that updates it.'
    '# "absent" means the path is not in the repository yet; adding it changes this file.'
    '#'
    '# Regenerate:  ./scripts/gates_lock.ps1'
    '# Verify:      ./scripts/gates_lock.ps1 -Verify'
    ''
)

$content = ($header + $entries) -join "`n"
$content += "`n"

if ($Verify) {
    if (-not (Test-Path -LiteralPath $LockPath)) {
        Write-Host 'gates.lock is missing. Run ./scripts/gates_lock.ps1' -ForegroundColor Red
        exit 1
    }
    $current = [System.IO.File]::ReadAllText($LockPath) -replace "`r`n", "`n"
    if ($current -ne $content) {
        Write-Host 'gates.lock does not match the protected inputs on disk.' -ForegroundColor Red
        Write-Host 'A protected input changed. Mats reviews and signs that change (section 2.1).'
        exit 1
    }
    Write-Host 'gates.lock matches the protected inputs.' -ForegroundColor Green
    exit 0
}

# LF, no BOM: .gitattributes keeps this file at LF in the repository and the working tree.
[System.IO.File]::WriteAllText($LockPath, $content, [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote gates.lock ($($entries.Count) entries)." -ForegroundColor Green
